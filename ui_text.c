void ui_text(SDL_Renderer *renderer, int x, int y, const char *text, int scale) {
  for (; *text; text++, x += 6 * scale) {
    int index = -1;
    if (*text >= '0' && *text <= '9')
      index = *text - '0';
    else if (*text >= 'A' && *text <= 'Z')
      index = 10 + *text - 'A';
    else if (*text == '/')
      index = 36;
    else if (*text == ':')
      index = 37;
    else if (*text == '-')
      index = 38;
    else if (*text == '_')
      index = 39;
    else if (*text == '+')
      index = 40;
    if (index < 0)
      continue;
    for (int column = 0; column < 5; column++) {
      for (int row = 0; row < 7; row++) {
        if (glyphs[index][column] & (1 << row)) {
          SDL_Rect pixel = {x + column * scale, y + row * scale, scale, scale};
          SDL_RenderFillRect(renderer, &pixel);
        }
      }
    }
  }
}
